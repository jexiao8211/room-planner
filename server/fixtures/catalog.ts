import type { ProductCandidate, ShapePart } from "../../src/shared/types";

export interface CatalogEntry extends Omit<ProductCandidate, "id" | "url"> {
  slug: string;
  /** Category words and synonyms used for keyword scoring (lowercase). */
  keywords: string[];
}

const box = (cx: number, cy: number, cz: number, sx: number, sy: number, sz: number, color?: string): ShapePart => ({
  kind: "box",
  center: { x: cx, y: cy, z: cz },
  size: { x: sx, y: sy, z: sz },
  ...(color ? { color } : {}),
});
const cyl = (cx: number, cy: number, cz: number, sx: number, sy: number, sz: number, color?: string): ShapePart => ({
  ...box(cx, cy, cz, sx, sy, sz, color),
  kind: "cylinder",
});
const sph = (cx: number, cy: number, cz: number, sx: number, sy: number, sz: number, color?: string): ShapePart => ({
  ...box(cx, cy, cz, sx, sy, sz, color),
  kind: "sphere",
});
const cone = (cx: number, cy: number, cz: number, sx: number, sy: number, sz: number, color?: string): ShapePart => ({
  ...box(cx, cy, cz, sx, sy, sz, color),
  kind: "cone",
});

/** Pendant: a thin cord from the ceiling plus a shade occupying the bottom `shadeFrac` of the bbox. */
function pendant(shade: "sphere" | "cylinder" | "cone", shadeFrac: number, cordColor = "#222222"): ShapePart[] {
  const cordFrac = 1 - shadeFrac;
  const shadePart =
    shade === "sphere"
      ? sph(0, shadeFrac / 2, 0, 1, shadeFrac, 1)
      : shade === "cone"
        ? cone(0, shadeFrac / 2, 0, 1, shadeFrac, 1)
        : cyl(0, shadeFrac / 2, 0, 1, shadeFrac, 1);
  return [
    cyl(0, 1 - 0.02, 0, 0.25, 0.04, 0.25, cordColor), // ceiling canopy
    cyl(0, shadeFrac + cordFrac / 2, 0, 0.025, cordFrac, 0.025, cordColor), // cord
    shadePart,
  ];
}

/** Four tapered-looking legs under a body; legs occupy the bottom `legFrac`. */
function legs(legFrac: number, inset = 0.42, thickness = 0.06, color?: string): ShapePart[] {
  return [
    [-1, -1],
    [1, -1],
    [-1, 1],
    [1, 1],
  ].map(([sx, sz]) => box(sx * inset, legFrac / 2, sz * inset, thickness, legFrac, thickness * 1.2, color));
}

